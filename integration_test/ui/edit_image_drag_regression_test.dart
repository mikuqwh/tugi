Future<String> _writeProbe() async {
  final dir = await getApplicationDocumentsDirectory();
  final file = File('${dir.path}/probe.png');
  await file.writeAsBytes(base64Decode(_pngB64), flush: true);
  return file.path;
}

/// Press exactly on a slider's THUMB.
///
/// A Slider only starts a drag when the gesture lands on the thumb, not
/// anywhere on the track -- so a test that presses the widget centre drags
/// nothing at all.
Offset _thumbPosition(WidgetTester tester, Finder sliderFinder) {
  final box = tester.getRect(sliderFinder);
  final slider = tester.widget<Slider>(sliderFinder);
  final span = slider.max - slider.min;
  final fraction = span == 0 ? 0.0 : (slider.value - slider.min) / span;
  // The track is inset by the thumb radius on both ends.
  return Offset(box.left + 12 + fraction * (box.width - 24), box.center.dy);
}

void main() {
  testWidgets('dragging a colour slider keeps the panel scroll position',
      (tester) async {
    final probe = await _writeProbe();

    await tester.pumpWidget(
      MaterialApp(home: EditImageScreen(initialImagePath: probe)),
    );
    await tester.pumpAndSettle(const Duration(seconds: 3));

    // Scroll down to the colour sliders.
    final panel = find.byType(ListView);
    for (var i = 0; i < 8 && find.byType(Slider).evaluate().isEmpty; i++) {
      await tester.drag(panel, const Offset(0, -600));
      await tester.pumpAndSettle();
    }
    expect(find.byType(Slider), findsWidgets);

    final slider = find.byType(Slider).first;
    await tester.ensureVisible(slider);
    await tester.pumpAndSettle();
    final offsetBefore =
        tester.widget<ListView>(panel).controller?.offset ?? 0.0;

    // Drag the slider.
    final gesture = await tester.startGesture(_thumbPosition(tester, slider));
    await tester.pump();
    await gesture.moveBy(const Offset(30, 0));
    await tester.pump();

    // DURING the drag the panel must still be there and must not have
    // jumped back to the top.
    expect(find.byType(ListView), findsOneWidget,
        reason: 'the control panel must survive the drag');
    final offsetDuring =
        tester.widget<ListView>(panel).controller?.offset ?? 0.0;
    expect(offsetDuring, offsetBefore,
        reason: 'the panel must not jump to the top while dragging');

    await gesture.up();
    await tester.pumpAndSettle();

    // And afterwards the panel is still where it was.
    expect(find.byType(ListView), findsOneWidget);
    final offsetAfter =
        tester.widget<ListView>(panel).controller?.offset ?? 0.0;
    expect(offsetAfter, offsetBefore,
        reason: 'the panel must not jump to the top after the drag');
  });
}
