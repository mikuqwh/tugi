#!/usr/bin/env bash
# Encoder matrix: run every registry format through a REAL ffmpeg and report
# what happens. Two things this catches that unit tests cannot:
#
#   1. a command shape the registry claims but ffmpeg rejects;
#   2. which codecs THIS machine's ffmpeg has (the device build differs -- the
#      shipped package has no libjxl, the host build does).
#
# The command list comes from `tool/formats/emit_commands.dart`, i.e. from the
# same registry the app uses, so there is no second table to drift.
set -u
cd "$(dirname "$0")/../.." || exit 1

OUT=tool/formats/matrix.md
TMP=tool/formats/.out
FFMPEG=${FFMPEG:-ffmpeg}
rm -rf "$TMP" && mkdir -p "$TMP"

FFVER=$("$FFMPEG" -hide_banner -version 2>/dev/null | head -1 | sed 's/ffmpeg version //;s/ Copyright.*//')
echo "ffmpeg: $FFVER"
echo

mapfile -t LINES < <(dart run tool/formats/emit_commands.dart 2>/dev/null)
if [ ${#LINES[@]} -eq 0 ]; then
  echo "emit_commands.dart produced nothing (dart run failed?)" >&2
  exit 1
fi

{
  echo "# Encoder matrix"
  echo
  echo "Generated by \`tool/formats/probe_matrix.sh\` against \`ffmpeg $FFVER\`."
  echo "Re-run it after changing the registry or the ffmpeg build."
  echo
  echo "| id | run | bytes | note |"
  echo "|---|---|---|---|"
} > "$OUT"

pass=0; fail=0
for line in "${LINES[@]}"; do
  IFS=$'\t' read -r id ext args <<< "$line"
  out="$TMP/$id.$ext"
  rm -f "$out"
  # shellcheck disable=SC2086
  if "$FFMPEG" -hide_banner -loglevel error -y $args "$out" > "$TMP/$id.log" 2>&1; then
    bytes=$(stat -c %s "$out" 2>/dev/null || echo 0)
    if [ "$bytes" -gt 0 ]; then
      echo "| \`$id\` | ✅ | $bytes | |" >> "$OUT"
      pass=$((pass+1))
      continue
    fi
    note="rc=0 but no file"
  else
    note=$(tail -1 "$TMP/$id.log" | tr '|' '/' | cut -c1-120)
  fi
  echo "| \`$id\` | ❌ | 0 | $note |" >> "$OUT"
  fail=$((fail+1))
done

echo
echo "PASS=$pass FAIL=$fail  →  $OUT"
[ "$fail" -eq 0 ]
